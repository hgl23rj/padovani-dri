function calcularMetas(stageId, grupoFiltro) {
  const resultado = [];
  for (const [key, n] of Object.entries(NUTRIENTS)) {
    if (grupoFiltro && grupoFiltro !== "todos" && n.grupo !== grupoFiltro) continue;
    const d = n.data[stageId];
    if (!d) continue;
    const [ear, rda, ul, isAI] = d;
    resultado.push({
      id: key,
      nome: n.nome,
      grupo: n.grupo,
      unidade: n.unidade,
      ulUnit: n.ulUnit || null,
      nota: n.nota || null,
      ear,
      rda,
      ul,
      isAI: !!isAI,
    });
  }
  return resultado;
}

function listarEstagios(sexo, condicao) {
  if (condicao === "gestante" && sexo === "F") return STAGES.gestante;
  if (condicao === "lactante" && sexo === "F") return STAGES.lactante;
  return STAGES[sexo] || STAGES.F;
}

